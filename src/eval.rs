pub fn evaluate(pos: &mut Position, net: Option<&Network>) -> i32 {
    if let Some(net) = net {
        nnue::evaluate(pos, net)
    } else {
        hce(pos)
    }
}

fn hce(pos: &Position) -> i32 {
    let mut score = 0i32;
    for sq in 0..64u8 {
        let p = pos.piece_on(Square(sq));
        if p == NO_PIECE {
            continue;
        }
        let pt = piece_type(p);
        let c = piece_color(p);
        let sq_idx = if c == Color::White {
            sq as usize
        } else {
            Square(sq).flip().idx()
        };
        let v = material_value(pt) + MG_PST[pt.idx()][sq_idx];
        if c == Color::White {
            score += v;
        } else {
            score -= v;
        }
    }
    if pos.side == Color::White {
        score
    } else {
        -score
    }
}
